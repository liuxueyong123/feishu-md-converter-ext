import { describe, expect, it } from "vitest";

import {
  detectMermaidSource,
  normalizeMermaidSource,
} from "../src/core/mermaid";

describe("normalizeMermaidSource", () => {
  it("removes Lark zero-width characters and normalizes line endings", () => {
    const source = "\u200B%%{init: {\"theme\":\"base\"}}%%\u200B\r\nflowchart LR\u2060\r\n  A --> B\uFEFF";

    expect(normalizeMermaidSource(source)).toBe(
      '%%{init: {"theme":"base"}}%%\nflowchart LR\n  A --> B',
    );
  });

  it("only trims blank lines at the source boundaries", () => {
    const source = "\n\nflowchart LR\n\n  A --> B\n\n";

    expect(normalizeMermaidSource(source)).toBe(
      "flowchart LR\n\n  A --> B",
    );
  });
});
describe("detectMermaidSource", () => {
  it("accepts a Mermaid init directive as sufficient evidence", () => {
    const result = detectMermaidSource(
      '%%{init: {"theme":"base"}}%%\nunsupportedFutureDiagram\nA --> B',
    );

    expect(result).toEqual({
      isMermaid: true,
      normalizedSource:
        '%%{init: {"theme":"base"}}%%\nunsupportedFutureDiagram\nA --> B',
      signature: "init",
    });
  });

  it.each([
    "flowchart LR",
    "graph TD",
    "sequenceDiagram",
    "classDiagram",
    "stateDiagram-v2",
    "erDiagram",
    "gantt",
    "mindmap",
    "timeline",
    "journey",
    "quadrantChart",
    "requirementDiagram",
    "gitGraph",
    "pie title Browser share",
    "C4Context",
  ])("accepts the Mermaid diagram signature %s", (signature) => {
    const result = detectMermaidSource(`${signature}\n  A --> B`);

    expect(result.isMermaid).toBe(true);
    expect(result.signature).toBe(signature.split(/\s/, 1)[0]);
  });

  it("skips Mermaid comments before the diagram signature", () => {
    const result = detectMermaidSource(
      "%% generated by an assistant\n\nflowchart LR\nA --> B",
    );

    expect(result.isMermaid).toBe(true);
    expect(result.signature).toBe("flowchart");
  });

  it("rejects an ordinary code block that mentions Mermaid later", () => {
    const result = detectMermaidSource(
      'const chartType = "flowchart";\nflowchart LR\nA --> B',
    );

    expect(result).toEqual({
      isMermaid: false,
      normalizedSource:
        'const chartType = "flowchart";\nflowchart LR\nA --> B',
      signature: null,
    });
  });

  it("rejects empty and comment-only code blocks", () => {
    expect(detectMermaidSource("\n\u200B\n").isMermaid).toBe(false);
    expect(detectMermaidSource("%% just a comment").isMermaid).toBe(false);
  });
});
